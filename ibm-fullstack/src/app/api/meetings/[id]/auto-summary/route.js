import { NextResponse } from 'next/server';
import { callWatsonx } from '@/lib/watsonx';
import connectDB from '@/lib/mongodb';
import Meeting from '@/models/Meeting';

export async function POST(request, { params }) {
  try {
    // Await params in Next.js 15
    const { id: meetingId } = await params;
    
    // Handle potential JSON parsing errors
    let requestBody;
    try {
      requestBody = await request.json();
    } catch (jsonError) {
      console.error('JSON parsing error:', jsonError);
      requestBody = {};
    }

    const { reason } = requestBody;

    console.log(`🤖 Auto-generating meeting summary for: ${meetingId} (${reason})`);

    // Connect to database and get meeting data
    await connectDB();
    
    let meeting = await Meeting.findOne({ meetingId });
    
    if (!meeting) {
      // If no meeting found in DB, it means no transcripts were saved
      console.log(`⚠️  No meeting found in database for ID: ${meetingId}`);
      return NextResponse.json({ 
        error: 'Meeting not found or no transcripts available',
        details: 'Cannot generate summary without transcripts'
      }, { status: 404 });
    }

    // Check if summary already exists
    if (meeting.summary && meeting.summary.trim()) {
      console.log(`ℹ️  Summary already exists for meeting: ${meetingId}`);
      return NextResponse.json({
        success: true,
        summary: meeting.summary,
        transcriptCount: meeting.transcripts?.length || 0,
        participants: meeting.participants || [],
        generatedAt: meeting.summaryGeneratedAt || meeting.updatedAt,
        meetingId,
        note: 'Summary already existed'
      });
    }

    const transcripts = meeting.transcripts || [];

    if (!transcripts || transcripts.length === 0) {
      console.log(`⚠️  No transcripts available for meeting: ${meetingId}`);
      return NextResponse.json({ 
        error: 'No transcripts available', 
        details: 'Cannot generate summary without transcripts'
      }, { status: 400 });
    }

    // Organize transcripts by speaker and time
    const organizedTranscripts = transcripts
      .sort((a, b) => new Date(a.timestamp) - new Date(b.timestamp))
      .map(t => {
        const time = new Date(t.timestamp).toLocaleTimeString();
        return `[${time}] ${t.userName || t.speaker}: ${t.text}`;
      })
      .join('\n');

    // Create a comprehensive prompt for the AI
    const summaryPrompt = `Please analyze the following meeting transcript and provide a comprehensive summary in a professional format.

MEETING TRANSCRIPT:
${organizedTranscripts}

Please provide a well-structured summary with the following sections:

**📋 MEETING OVERVIEW**
Brief summary of the main topics and purpose of the meeting.

**🎯 KEY DISCUSSION POINTS**
- List the main topics discussed
- Important decisions made
- Key insights shared

**✅ ACTION ITEMS & NEXT STEPS**
- Specific tasks assigned
- Deadlines mentioned
- Follow-up actions required

**👥 PARTICIPANT CONTRIBUTIONS**
- Key speakers and their main contributions
- Different perspectives shared

**⏰ MEETING DETAILS**
- Duration and key timing information
- Important milestones during the meeting

Format the response in clear, professional language suitable for meeting minutes. Use bullet points and clear headings for easy reading.`;

    // Call WatsonX for summary generation
    const body = {
      messages: [
        {
          role: 'user',
          content: summaryPrompt
        }
      ],
      project_id: process.env.WATSONX_PROJECT_ID,
      model_id: process.env.WATSONX_MODEL_ID || 'ibm/granite-3-3-8b-instruct',
      temperature: 0.3,
      max_tokens: 1200,
    };

    console.log('📤 Calling WatsonX for auto-generated meeting summary...');
    const data = await callWatsonx('/ml/v1/text/chat?version=2023-05-29', body);

    // Extract the response from WatsonX format
    const summary = data?.choices?.[0]?.message?.content || 
                   data?.results?.[0]?.generated_text || 
                   data?.output || 
                   'Could not generate meeting summary.';

    console.log('✅ Auto-generated meeting summary completed');

    // Update meeting with summary
    try {
      meeting.summary = summary;
      meeting.summaryGeneratedAt = new Date();
      meeting.status = 'ended';
      meeting.endedAt = meeting.endedAt || new Date();
      meeting.updatedAt = new Date();
      
      await meeting.save();
      console.log('💾 Auto-generated meeting summary saved to database');
      
    } catch (dbError) {
      console.error('Database save error:', dbError);
      // Continue even if DB save fails
    }

    return NextResponse.json({
      success: true,
      summary,
      transcriptCount: transcripts.length,
      participants: meeting.participants || [],
      generatedAt: new Date().toISOString(),
      meetingId,
      reason: reason || 'auto-generated',
      autoGenerated: true
    });

  } catch (error) {
    console.error('❌ Auto meeting summary generation error:', error);
    return NextResponse.json({ 
      error: 'Failed to auto-generate meeting summary', 
      details: String(error)
    }, { status: 500 });
  }
}
